static uint8_t display_buffer[SSD1306_WIDTH * SSD1306_HEIGHT / 8];

void ssd1306_write_cmd(uint8_t cmd) {
    uint8_t buf[2] = {0x00, cmd};
    i2c_write_blocking(TARGET_I2C_PORT, SSD1306_I2C_ADDR, buf, 2, false);
}

void ssd1306_init(void) {
    ssd1306_write_cmd(0xAE); 
    ssd1306_write_cmd(0x20); 
    ssd1306_write_cmd(0x00); // Horizontal addressing mode
    ssd1306_write_cmd(0xB0); 
    ssd1306_write_cmd(0xC8); 
    ssd1306_write_cmd(0x00); 
    ssd1306_write_cmd(0x10); 
    ssd1306_write_cmd(0x40); 
    ssd1306_write_cmd(0x81); 
    ssd1306_write_cmd(0x7F);
    ssd1306_write_cmd(0xA1); 
    ssd1306_write_cmd(0xA6); 
    
    // Dynamic Multiplex Ratio adaptation
    ssd1306_write_cmd(0xA8); 
    ssd1306_write_cmd(SSD1306_HEIGHT - 1); 

    ssd1306_write_cmd(0xA4); 
    ssd1306_write_cmd(0xD3); 
    ssd1306_write_cmd(0x00); 
    ssd1306_write_cmd(0xD5); 
    ssd1306_write_cmd(0x80); 
    
    // Dynamic Pre-charge period layout profile
    ssd1306_write_cmd(0xD9); 
    ssd1306_write_cmd((SSD1306_HEIGHT == 64) ? 0xF1 : 0x22);

    // Dynamic COM Pin hardware layout profiles
    ssd1306_write_cmd(0xDA); 
    ssd1306_write_cmd((SSD1306_HEIGHT == 64) ? 0x12 : 0x02);

    ssd1306_write_cmd(0xDB); 
    ssd1306_write_cmd(0x20); 
    ssd1306_write_cmd(0x8D); 
    ssd1306_write_cmd(0x14); 
    ssd1306_write_cmd(0xAF); 
    ssd1306_clear();
    ssd1306_show();
}

void ssd1306_clear(void) {
    memset(display_buffer, 0x00, sizeof(display_buffer));
}

void ssd1306_show(void) {
    ssd1306_write_cmd(0x21); 
    ssd1306_write_cmd(0);   
    ssd1306_write_cmd(127); 
    
    ssd1306_write_cmd(0x22); 
    ssd1306_write_cmd(0);   
    ssd1306_write_cmd((SSD1306_HEIGHT / 8) - 1);   

    uint8_t payload[sizeof(display_buffer) + 1];
    payload[0] = 0x40; 
    memcpy(&payload[1], display_buffer, sizeof(display_buffer));
    i2c_write_blocking(TARGET_I2C_PORT, SSD1306_I2C_ADDR, payload, sizeof(payload), false);
}

void ssd1306_draw_char(int x, int y, char c) {
    if (c < 32 || c > 90) c = 32; 
    int idx = c - 32;

    for (int col = 0; col < 5; col++) {
        uint8_t line = font5x7[idx][col];
        for (int row = 0; row < 7; row++) {
            if (line & (1 << row)) {
                // Apply spatial dilation when scaling is set to 2
                if (text_scale == 2) {
                    for (int sx = 0; sx < 2; sx++) {
                        for (int sy = 0; sy < 2; sy++) {
                            int px = x + (col * 2) + sx;
                            int py = y + (row * 2) + sy;
                            if (px >= 0 && px < SSD1306_WIDTH && py >= 0 && py < SSD1306_HEIGHT) {
                                display_buffer[px + (py / 8) * SSD1306_WIDTH] |= (1 << (py % 8));
                            }
                        }
                    }
                } else {
                    // Fall back to standard 1:1 pixel rendering
                    int px = x + col;
                    int py = y + row;
                    if (px >= 0 && px < SSD1306_WIDTH && py >= 0 && py < SSD1306_HEIGHT) {
                        display_buffer[px + (py / 8) * SSD1306_WIDTH] |= (1 << (py % 8));
                    }
                }
            }
        }
    }
}

void ssd1306_draw_string(int x, int y, const char* str) {
    int spacing = (text_scale == 2) ? 12 : 6;
    while (*str) {
        ssd1306_draw_char(x, y, *str);
        x += spacing; 
        str++;
    }
}
